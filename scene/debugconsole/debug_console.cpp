Point2i TextConsole::_write(const String &p_msg, Point2i pos, ColorIndex foreground, ColorIndex background) {
	ERR_FAIL_COND_V(_screen == 0, pos);
	ERR_FAIL_COND_V(pos.x >= _con_size.width, pos);
	ERR_FAIL_COND_V(pos.y >= _con_size.height, pos);

	// Resolve COLOR_DEFAULT here: it is a sentinel, not a palette entry, and inverting a
	// cell swaps the background into the foreground where it would index palette[] out of
	// bounds.
	if (foreground == COLOR_DEFAULT) {
		foreground = _default_fg_color_index;
	}
	if (background == COLOR_DEFAULT) {
		background = _default_bg_color_index;
	}

	// \x01 toggles the glyph bank for the characters that follow, except that \x01\x01 is
	// not a toggle of a toggle: it draws code 1 of bank 1, which is what keeps that code
	// usable as a glyph slot of its own. Bank 1 holds the patched glyphs, and any code
	// without one is rendered as the inverted bank 0 glyph, see _update_mesh().
	uint8_t bank = BANK_CP437;
	const CharString ascii = p_msg.ascii();
	// length(), not size(): CharString::size() counts the null terminator, and writing it
	// would draw a stray cell and advance the cursor past the end of the text.
	for (int i = 0; i < ascii.length(); ++i) {
		uint8_t cell_bank = bank;
		char code = ascii[i];
		if (ascii[i] == '\x01') {
			if (i + 1 >= ascii.length()) {
				break; // dangling escape, nothing to draw
			}
			if (ascii[i + 1] == '\x01') {
				++i;
				cell_bank = BANK_PATCH;
				code = ascii[i];
			} else {
				bank = (bank == BANK_CP437) ? BANK_PATCH : BANK_CP437;
				continue;
			}
		}
		const cell c = { code, foreground, background, cell_bank, false };
		_screen[pos.y * _con_size.width + pos.x] = c;
		pos.x++;
		if (pos.x == _con_size.width)
			pos = Point2i(0, pos.y + 1);
		if (pos.y == _con_size.height) {
			_scroll_up();
			pos = Point2i(pos.x, pos.y - 1);
		}
	}
	_dirty_screen = true;
	return pos;
}

Point2i TextConsole::_put(const String &p_msg, Point2i pos, ColorIndex foreground, ColorIndex background) {
	ERR_FAIL_COND_V(_screen == 0, pos);
	ERR_FAIL_COND_V(pos.x >= _con_size.width, pos);
	ERR_FAIL_COND_V(pos.y >= _con_size.height, pos);

	// Resolve COLOR_DEFAULT here: it is a sentinel, not a palette entry, and inverting a
	// cell swaps the background into the foreground where it would index palette[] out of
	// bounds.
	if (foreground == COLOR_DEFAULT) {
		foreground = _default_fg_color_index;
	}
	if (background == COLOR_DEFAULT) {
		background = _default_bg_color_index;
	}

	// \x01 toggles the glyph bank for the characters that follow, except that \x01\x01 is
	// not a toggle of a toggle: it draws code 1 of bank 1, which is what keeps that code
	// usable as a glyph slot of its own. Bank 1 holds the patched glyphs, and any code
	// without one is rendered as the inverted bank 0 glyph, see _update_mesh().
	uint8_t bank = BANK_CP437;
	const CharString ascii = p_msg.ascii();
	for (int i = 0; i < ascii.length(); ++i) {
		uint8_t cell_bank = bank;
		char code = ascii[i];
		if (ascii[i] == '\x01') {
			if (i + 1 >= ascii.length()) {
				break; // dangling escape, nothing to draw
			}
			if (ascii[i + 1] == '\x01') {
				++i;
				cell_bank = BANK_PATCH;
				code = ascii[i];
			} else {
				bank = (bank == BANK_CP437) ? BANK_PATCH : BANK_CP437;
				continue;
			}
		}
		const cell c = { code, foreground, background, cell_bank, false };
		if (pos.x < _con_size.width) {
			_screen[pos.y * _con_size.width + pos.x] = c;
			pos.x++;
		}
	}
	_dirty_screen = true;
	return pos;
}

void TextConsole::put_cell(int p_x, int p_y, uint8_t p_code, ColorIndex p_fg, ColorIndex p_bg, Bank p_bank) {
	if (_screen == nullptr) {
		return;
	}
	// Silent clip: a widget draws by poking cells and must not fault on coordinates that
	// fall outside the grid, so out-of-range writes are dropped rather than reported.
	if (p_x < 0 || p_y < 0 || p_x >= _con_size.width || p_y >= _con_size.height) {
		return;
	}
	// COLOR_DEFAULT is a sentinel, not a palette entry; resolve it the way _write()/_put() do.
	if (p_fg == COLOR_DEFAULT) {
		p_fg = _default_fg_color_index;
	}
	if (p_bg == COLOR_DEFAULT) {
		p_bg = _default_bg_color_index;
	}
	const cell c = { char(p_code), p_fg, p_bg, uint8_t(p_bank), false };
	_screen[p_y * _con_size.width + p_x] = c;
	_dirty_screen = true;
}

void TextConsole::put_text(int p_x, int p_y, const String &p_text, ColorIndex p_fg, ColorIndex p_bg) {
	if (_screen == nullptr) {
		return;
	}
	// The same escape grammar as _write()/_put() -- and it must stay in step with them --
	// but every resolved cell goes through put_cell(), so a run that begins off the left
	// edge or overruns the right one simply loses the cells that fall outside instead of
	// wrapping or scrolling. Bank toggles advance nothing, matching the writers.
	uint8_t bank = BANK_CP437;
	const CharString ascii = p_text.ascii();
	int x = p_x;
	for (int i = 0; i < ascii.length(); ++i) {
		uint8_t cell_bank = bank;
		char code = ascii[i];
		if (ascii[i] == '\x01') {
			if (i + 1 >= ascii.length()) {
				break; // dangling escape, nothing to draw
			}
			if (ascii[i + 1] == '\x01') {
				++i;
				cell_bank = BANK_PATCH;
				code = ascii[i];
			} else {
				bank = (bank == BANK_CP437) ? BANK_PATCH : BANK_CP437;
				continue;
			}
		}
		put_cell(x, p_y, uint8_t(code), p_fg, p_bg, Bank(cell_bank));
		++x;
	}
}

void TextConsole::fill_rect(int p_x, int p_y, int p_w, int p_h, uint8_t p_code, ColorIndex p_fg, ColorIndex p_bg, Bank p_bank) {
	for (int dy = 0; dy < p_h; ++dy) {
		for (int dx = 0; dx < p_w; ++dx) {
			put_cell(p_x + dx, p_y + dy, p_code, p_fg, p_bg, p_bank);
		}
	}
}

bool TextConsole::get_cell(int p_x, int p_y, cell &r_cell) const {
	if (_screen == nullptr) {
		return false;
	}
	if (p_x < 0 || p_y < 0 || p_x >= _con_size.width || p_y >= _con_size.height) {
		return false;
	}
	r_cell = _screen[p_y * _con_size.width + p_x];
	return true;
}

void TextConsole::_scroll_up(int p_scroll_lines) {
	ERR_FAIL_COND(p_scroll_lines <= 0);
	ERR_FAIL_COND(_screen == 0);

	const int cell_size = sizeof(cell);
	memmove(_screen, _screen + _con_size.width * p_scroll_lines, (_con_size.height - p_scroll_lines) * _con_size.width * cell_size * p_scroll_lines);
	memset(_screen + (_con_size.height - p_scroll_lines) * _con_size.width, 0, _con_size.width * cell_size * p_scroll_lines);
}

bool TextConsole::_resolve_cell(const cell &p_cell, resolved_cell &r_out) const {
	if (!p_cell.character) {
		return false;
	}

	const uint8_t code = uint8_t(p_cell.character);
	uint8_t fg = p_cell.foreground;
	uint8_t bg = p_cell.background;

	// Bank 1 only carries the patched glyphs. Any other code in that bank is drawn by
	// inverting the bank 0 glyph, which is what makes the \x01 bank toggle behave like the
	// invert marker it replaced.
	uint8_t bank = p_cell.bank;
	bool invert = p_cell.inverted;
	if (bank == BANK_PATCH && !_has_patch[code]) {
		bank = BANK_CP437;
		invert = !invert;
	}

	if (invert) {
		SWAP(fg, bg);
		// Drawing the glyph in a transparent colour would not punch a hole in the
		// background block, it would simply make the character disappear.
		if (fg == COLOR_TRANSPARENT) {
			fg = COLOR_BLACK;
		}
	}

	r_out.code = code;
	r_out.foreground = fg;
	r_out.background = bg;
	r_out.bank = bank;
	return true;
}

void TextConsole::_update_mesh() {
	ERR_FAIL_COND(_screen == 0);

	// Char corners, scaled by pixel_scale. Not `static`: both the face and the zoom can
	// change at runtime, and a cached first-font cell size would freeze the whole grid.
	const Size2i cell_size = get_cell_size();
	const Point2i v0(0, 0); /* 0, 0 */
	const Point2i v1(0, cell_size.height); /* 0, 1 */
	const Point2i v2(cell_size.width, 0); /* 1, 0 */
	const Point2i v3(cell_size.width, cell_size.height); /* 1, 1 */

	PoolVector2Array vertices;
	PoolColorArray bg_colors, fg_colors;
	PoolVector2Array textures;

	Point2i xx;
	cell *p = _screen;
	for (int row = 0; row < _con_size.height; ++row) {
		for (int col = 0; col < _con_size.width; ++col) {
			resolved_cell rc;
			if (_resolve_cell(*p, rc)) {
				const int tex_info = rc.code + rc.bank * 256;
				const uint8_t fg = rc.foreground;
				const uint8_t bg = rc.background;

				vertices.push_back(xx + v0);
				vertices.push_back(xx + v1);
				vertices.push_back(xx + v2);
				vertices.push_back(xx + v1);
				vertices.push_back(xx + v2);
				vertices.push_back(xx + v3);
				// bg:
				bg_colors.push_multi(6, palette[bg]);
				// fg:
				textures.push_back(_chars[tex_info].t[0]);
				textures.push_back(_chars[tex_info].t[1]);
				textures.push_back(_chars[tex_info].t[2]);
				textures.push_back(_chars[tex_info].t[1]);
				textures.push_back(_chars[tex_info].t[2]);
				textures.push_back(_chars[tex_info].t[3]);
				fg_colors.push_multi(6, palette[fg]);
			}
			xx += v2;
			p++;
		}
		xx = Point2i(0, xx.y + cell_size.height);
	}

	Array background, foreground;
	background.resize(VS::ARRAY_MAX);
	background[VS::ARRAY_VERTEX] = vertices;
	background[VS::ARRAY_COLOR] = bg_colors;
	foreground.resize(VS::ARRAY_MAX);
	foreground[VS::ARRAY_VERTEX] = vertices;
	foreground[VS::ARRAY_TEX_UV] = textures;
	foreground[VS::ARRAY_COLOR] = fg_colors;

	if (vertices.size() == 0) {
		_mesh = Ref<ArrayMesh>();
		_mesh_bg = Ref<ArrayMesh>();
	} else {
		// The background surface carries no UVs, so it must be drawn without the glyph atlas
		// bound: otherwise it samples texel (0,0) and is modulated by whatever happens to be
		// there (in the current atlas, the transparent corner of glyph 0).
		_mesh_bg = newref(ArrayMesh);
		_mesh_bg->add_surface_from_arrays(Mesh::PRIMITIVE_TRIANGLES, background, Array(), Mesh::ARRAY_FLAG_USE_2D_VERTICES);
		_mesh = newref(ArrayMesh);
		_mesh->add_surface_from_arrays(Mesh::PRIMITIVE_TRIANGLES, foreground, Array(), Mesh::ARRAY_FLAG_USE_2D_VERTICES);
	}
}

void TextConsole::draw(RID p_canvas_item, const Transform2D &p_xform) {
	ERR_FAIL_COND(!_font_cache[_font_face].is_valid());

	if (_dirty_screen) {
		_update_mesh();
		_dirty_screen = false;
	}

	if (_mesh_bg.is_valid()) {
		VS::get_singleton()->canvas_item_add_mesh(p_canvas_item, _mesh_bg->get_rid(), p_xform, Color(1, 1, 1, 1), RID(), RID());
	}
	if (_mesh.is_valid()) {
		RID texture_rid = _font_cache[_font_face]->get_rid();
		VS::get_singleton()->canvas_item_add_mesh(p_canvas_item, _mesh->get_rid(), p_xform, Color(1, 1, 1, 1), texture_rid, RID());
	}
}

void TextConsole::set_pixel_scale(int p_scale) {
	const int scale = CLAMP(p_scale, 1, CONSOLE_MAX_PIXEL_SCALE);
	if (scale == pixel_scale) {
		return;
	}
	pixel_scale = scale;
	_dirty_screen = true;
}

// Grid limits win over the physical target size: a 27 column console is useless no matter
// how crisp it is. See CONSOLE.md section 6.
static const int CONSOLE_MIN_COLS = 40, CONSOLE_MIN_ROWS = 20, CONSOLE_MAX_COLS = 120;
static const real_t CONSOLE_TARGET_MM = 3.2; // cell height at a natural viewing distance

static int _fit_scale(const Size2i &p_cell, const Size2i &p_viewport, int p_dpi) {
	const real_t px_per_mm = p_dpi / 25.4;
	int scale = CLAMP(int(Math::round(px_per_mm * CONSOLE_TARGET_MM / p_cell.height)), 1, CONSOLE_MAX_PIXEL_SCALE);

	if (p_viewport.width > 0 && p_viewport.height > 0) {
		while (scale > 1 && (p_viewport.width / (p_cell.width * scale) < CONSOLE_MIN_COLS || p_viewport.height / (p_cell.height * scale) < CONSOLE_MIN_ROWS)) {
			scale--; // too zoomed in to fit a usable grid
		}
		while (scale < CONSOLE_MAX_PIXEL_SCALE && p_viewport.width / (p_cell.width * scale) > CONSOLE_MAX_COLS) {
			scale++; // too many columns, the text would be unreadably small
		}
	}
	return scale;
}

static bool _grid_fits(const Size2i &p_cell, const Size2i &p_viewport, int p_scale) {
	if (p_viewport.width <= 0 || p_viewport.height <= 0) {
		return true;
	}
	const int cols = p_viewport.width / (p_cell.width * p_scale);
	const int rows = p_viewport.height / (p_cell.height * p_scale);
	return cols >= CONSOLE_MIN_COLS && cols <= CONSOLE_MAX_COLS && rows >= CONSOLE_MIN_ROWS;
}

void console_auto_font(int p_dpi, const Size2i &p_viewport, TextConsole::FontSize &r_face, int &r_scale) {
	const int dpi = p_dpi > 0 ? p_dpi : 72;

	// 8x12 is the default: the best density/legibility trade-off of the five faces. The
	// others are only reached when the scale knob alone cannot satisfy the grid limits --
	// 4x6 when the screen is too small (or too wide) even at scale 1, 8x16 when it is so
	// dense that the zoom saturates.
	static const TextConsole::FontSize order[] = { TextConsole::DOS_8x12, TextConsole::DOS_4x6, TextConsole::DOS_8x16 };

	for (int i = 0; i < 3; ++i) {
		const Size2i cell = Size2i(embed_debug_font[order[i]].char_w, embed_debug_font[order[i]].char_h);
		const int scale = _fit_scale(cell, p_viewport, dpi);
		if (i == 2 || _grid_fits(cell, p_viewport, scale)) {
			r_face = order[i];
			r_scale = scale;
			return;
		}
	}
}

