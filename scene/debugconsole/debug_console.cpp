void ConsoleInstance::_poll_secondary_touch() {
	SecondaryDisplay *display = SecondaryDisplay::get_singleton();
	if (!display || secondary_mode == SECONDARY_NEVER) {
		return;
	}

	if (!panel_touch) {
		// Opt-out by default: a panel that reacts to taps is a panel the player can hit by
		// accident, and on some platforms its window competes with the game for input focus.
		// The queue is still drained so enabling it later does not replay old taps.
		SecondaryDisplay::TouchEvent discarded;
		while (display->pop_touch(discarded)) {
		}
		touch_down = false;
		return;
	}

	// The threshold is generous: the panel is usually a small strip and a deliberate
	// "hide" gesture should not be triggered by a slow page tap.
	static int long_press_msec = -1;
	if (long_press_msec == -1) {
		long_press_msec = MAX(100, (int)GLOBAL_DEF("debug/console/long_press_msec", 600));
	}

	SecondaryDisplay::TouchEvent ev;
	while (display->pop_touch(ev)) {
		if (ev.pressed) {
			touch_down = true;
			touch_down_msec = ev.time_msec;
			continue;
		}
		if (!touch_down) {
			continue; // release without a matching press (surface was re-attached)
		}
		touch_down = false;
		const uint64_t held = ev.time_msec > touch_down_msec ? ev.time_msec - touch_down_msec : 0;
		const bool long_press = (int)held >= long_press_msec;
		if (!is_visible_in_tree()) {
			// Any tap brings a long-press-hidden console back; there is no other way in
			// on a device whose only input is this panel.
			if (!long_press) {
				set_visible(true);
				dirty = true;
			}
		} else if (long_press) {
			set_visible(false);
		} else {
			next_page();
		}
	}
}

void ConsoleInstance::_blank_secondary() {
	SecondaryDisplay *display = SecondaryDisplay::get_singleton();
	if (!display || secondary_mode == SECONDARY_NEVER || !display->is_available()) {
		return;
	}
	if (!secondary_active) {
		return; // never took the panel over, nothing of ours is on it
	}
	int stride_px = 0;
	Size2i locked;
	uint32_t *bits = display->lock_buffer(stride_px, locked);
	if (!bits) {
		return;
	}
	for (int y = 0; y < locked.height; ++y) {
		uint32_t *row = bits + y * stride_px;
		for (int x = 0; x < locked.width; ++x) {
			row[x] = 0xff000000;
		}
	}
	display->unlock_and_post();
}

void ConsoleInstance::_present_secondary() {
	SecondaryDisplay *display = SecondaryDisplay::get_singleton();
	if (secondary_mode == SECONDARY_NEVER) {
		display = nullptr; // the panel is opted out of; stay an overlay
	}
	if (!display || !display->is_available()) {
		if (secondary_active) {
			// The panel was unplugged: fall back to the main viewport geometry.
			secondary_active = false;
			secondary_size = Size2i();
			_auto_select_font();
			_apply_font();
			update(); // the overlay takes over again
		}
		return;
	}

	const Size2i size = display->get_size();
	if (!secondary_active || secondary_size != size) {
		const bool was_active = secondary_active;
		secondary_active = true;
		secondary_size = size;
		_adopt_secondary_geometry(size, display->get_dpi());
		if (!was_active) {
			update(); // clear whatever the overlay had drawn on the game viewport
		}
	}
	if (dirty) {
		_render();
	}

	int stride_px = 0;
	Size2i locked;
	uint32_t *bits = display->lock_buffer(stride_px, locked);
	if (!bits) {
		return;
	}

	// The console leaves COLOR_TRANSPARENT cells untouched, so the panel gets an opaque
	// black background of its own rather than whatever the surface held before.
	for (int y = 0; y < locked.height; ++y) {
		uint32_t *row = bits + y * stride_px;
		for (int x = 0; x < locked.width; ++x) {
			row[x] = 0xff000000; // opaque black, same bytes in ARGB32 and ABGR32
		}
	}
	console_blit(**console, bits, stride_px, locked.width, locked.height, CONSOLE_PIXEL_ABGR32);

	display->unlock_and_post();
}

// Everything a console needs before it can render, with no dependency on the scene tree:
// the grid, the logger claim, and the banner. Shared by NOTIFICATION_ENTER_TREE and
// render_offscreen(). Idempotent.
void ConsoleInstance::_bootstrap() {
	if (!console.is_valid()) {
		console = newref(TextConsole);
		if (auto_font) {
			// An explicit set_font()/set_pixel_scale() made before the first render pins the
			// choice, exactly as one made afterwards does.
			_auto_select_font();
		}
		_apply_font();
	}
	{
		MutexLock lock(active_mutex);
		active = this;
		_drain_backlog();
	}
	if (log_lines.empty()) {
		Vector<String> text;
		Vector<int> color;
		console_banner_lines(text, color);
		for (int i = 0; i < text.size(); ++i) {
			_push_line(text[i], TextConsole::ColorIndex(color[i]), TextConsole::COLOR_DEFAULT);
		}
	}
}

void ConsoleInstance::render_offscreen(int p_cols, int p_rows) {
	_bootstrap();
	ERR_FAIL_COND(!console.is_valid());
	if (p_cols > 0 && p_rows > 0) {
		console->resize(p_cols, p_rows);
	}
	_render(); // update() is a no-op outside the tree, so this only touches the grid
}

void ConsoleInstance::_notification(int p_notification) {
	switch (p_notification) {
		case NOTIFICATION_ENTER_TREE: {
			_bootstrap();
			if (Viewport *viewport = get_viewport()) {
				if (!viewport->is_connected("size_changed", this, "_viewport_size_changed")) {
					viewport->connect("size_changed", this, "_viewport_size_changed");
				}
			}
			set_process_internal(true);
			_render();
		} break;

		case NOTIFICATION_INTERNAL_PROCESS: {
			_poll_secondary_touch();
			if (!is_visible_in_tree()) {
				// Hidden by a long press: keep draining touches (a tap brings it back) but
				// leave the panel blank rather than a frozen snapshot.
				_blank_secondary();
				break;
			}
			// PAGE_LOG only redraws when something was logged; the polled pages tick at
			// refresh_rate so a busy watch table cannot eat the frame budget.
			const real_t delta = get_process_delta_time();
			refresh_accum += delta;
			const real_t period = refresh_rate > 0 ? 1.0 / refresh_rate : 0.2;
			if (refresh_accum >= period) {
				refresh_accum = 0;
				if (page != PAGE_LOG) {
					_poll_watches();
					dirty = true;
				}
			}
			if (dirty) {
				_render();
			}
			_present_secondary();
		} break;

		case NOTIFICATION_EXIT_TREE: {
			{
				MutexLock lock(active_mutex);
				if (active == this) {
					active = nullptr;
				}
			}
			if (Viewport *viewport = get_viewport()) {
				if (viewport->is_connected("size_changed", this, "_viewport_size_changed")) {
					viewport->disconnect("size_changed", this, "_viewport_size_changed");
				}
			}
		} break;

		case NOTIFICATION_DRAW: {
			// While the auxiliary panel owns the console the game viewport is left clean;
			// drawing both would show the same text twice (CONSOLE.md section 11).
			// "always" keeps the game screen clean even when no panel is attached.
			if (secondary_active || secondary_mode == SECONDARY_ALWAYS) {
				break;
			}
			if (console.is_valid()) {
				console->draw(get_canvas_item(), get_global_transform().affine_inverse());
			}
		} break;
	}
}

void ConsoleInstance::console_msg(const String &p_msg) {
	// parse control characters; the parsed lines land in the ring buffer, not on the grid
	_process_codes(p_msg);
	if (page == PAGE_LOG) {
		_render();
	}
}

