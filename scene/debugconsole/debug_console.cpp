typedef struct {
	const char *image;
	const unsigned char *pixels;
	int char_w, char_h, size, width, height, channels;
	const unsigned char *patch; // bank 1 glyph blocks, char_w * char_h bytes each
	const unsigned char *patch_codes; // the code each block belongs to
	int patch_count;
} EmbedImageItem;

