static PoolByteArray _poolbytearray_from_data(const uint8_t *bytes, size_t bytes_size, int bytes_channels, Image::Format dest_format) {
	PoolByteArray data;
	if (bytes_channels == FORMAT_1CHANNEL && dest_format == Image::Format::FORMAT_LA8) {
		data.resize(2 * bytes_size);
		PoolByteArray::Write wr = data.write();
		for (size_t b = 0; b < 2 * bytes_size; b += 2) {
			wr[b] = wr[b + 1] = bytes[b >> 1];
		}
	} else if (bytes_channels == FORMAT_1CHANNEL && dest_format == Image::Format::FORMAT_RGB8) {
		data.resize(3 * bytes_size);
		PoolByteArray::Write wr = data.write();
		for (size_t b = 0; b < 3 * bytes_size; b += 3) {
			wr[b] = wr[b + 1] = wr[b + 3] = bytes[b / 3];
		}
	} else if (bytes_channels == FORMAT_1CHANNEL && dest_format == Image::Format::FORMAT_RGBA8) {
		data.resize(4 * bytes_size);
		PoolByteArray::Write wr = data.write();
		for (size_t b = 0; b < 4 * bytes_size; b += 4) {
			wr[b] = wr[b + 1] = wr[b + 3] = wr[b + 4] = bytes[b >> 2];
		}
	} else {
		data.resize(bytes_size);
		memcpy(data.write().ptr(), bytes, bytes_size);
	}
	return data;
}

static Ref<Texture> _font_cache[TextConsole::DosFontCount];

static Image::Format _atlas_format(int p_channels) {
	constexpr Image::Format formats[] = {
		Image::Format::FORMAT_MAX,
		Image::Format::FORMAT_LA8,
		Image::Format::FORMAT_LA8,
		Image::Format::FORMAT_RGBA8,
		Image::Format::FORMAT_RGBA8,
	};
	return formats[p_channels];
}

void TextConsole::cleanup_font_cache() {
	for (int i = 0; i < DosFontCount; ++i) {
		_font_cache[i].unref();
	}
}

void TextConsole::load_font(FontSize p_font) {
	ERR_FAIL_INDEX(p_font, DosFontCount);

	const EmbedImageItem &data = embed_debug_font[p_font];

	if (!_font_cache[p_font].is_valid()) {
		const Image::Format format = _atlas_format(data.channels);

		// The embedded data only holds the 256 bank 0 glyphs. Allocate a texture of
		// BANK_COUNT times that height: bank 1 carries the patched glyphs at their own code
		// index (every other bank 1 code stays blank and is rendered by inverting the bank 0
		// glyph in _update_mesh()), and bank 2 is left blank for the runtime generators.
		PoolByteArray pixels = _poolbytearray_from_data(data.pixels, data.size, data.channels, format);
		const int static_size = pixels.size();
		const int channels = pixels.size() / data.size;
		pixels.resize(static_size * BANK_COUNT);
		{
			PoolByteArray::Write wr = pixels.write();
			memset(wr.ptr() + static_size, 0, static_size * (BANK_COUNT - 1));

			for (int i = 0; i < data.patch_count; ++i) {
				const int code = data.patch_codes[i];
				const int gx = (code % 16) * data.char_w;
				const int gy = (code / 16) * data.char_h;
				const uint8_t *src = data.patch + i * data.char_w * data.char_h;
				for (int y = 0; y < data.char_h; ++y) {
					uint8_t *dst = wr.ptr() + static_size + ((gy + y) * data.width + gx) * channels;
					for (int x = 0; x < data.char_w; ++x) {
						for (int c = 0; c < channels; ++c) {
							dst[x * channels + c] = src[y * data.char_w + x];
						}
					}
				}
			}
		}

		Ref<Image> image = newref(Image);
		image->create(data.width, data.height * BANK_COUNT, false, format, pixels);
		Ref<ImageTexture> font_texture = newref(ImageTexture);
		font_texture->create_from_image(image, 0);
		_font_cache[p_font] = font_texture;

		_register_global_ref(_font_cache[p_font]);
	}

	_font_face = p_font;
	_font_size = Size2i(data.char_w, data.char_h);

	// Which codes actually have a bank 1 glyph; the rest fall back to inversion.
	memset(_has_patch, 0, sizeof(_has_patch));
	for (int i = 0; i < data.patch_count; ++i) {
		_has_patch[data.patch_codes[i]] = true;
	}

	// 16 columns across, 16 rows per bank, BANK_COUNT banks stacked vertically.
	const real_t du = 1.0 / 16.0;
	const real_t dv = 1.0 / (16.0 * BANK_COUNT);
	for (int ch = 0; ch < 256 * BANK_COUNT; ++ch) {
		const real_t cx = (ch % 16) * du;
		const real_t cy = (ch / 16) * dv;

		_chars[ch].t[0] = Point2(cx, cy); /* 0, 0 */
		_chars[ch].t[1] = Point2(cx, cy + dv); /* 0, 1 */
		_chars[ch].t[2] = Point2(cx + du, cy); /* 1, 0 */
		_chars[ch].t[3] = Point2(cx + du, cy + dv); /* 1, 1 */
	}
}

void TextConsole::clear() {
	ERR_FAIL_COND(_screen == 0);
	memset(_screen, 0, sizeof(cell) * _con_size.width * _con_size.height);
	_cursor_pos = Point2i(0, 0);
	_dirty_screen = true;
}

