void ConsoleInstance::log_figlet(TextConsole::FigFontFace p_face, const String &p_msg, TextConsole::ColorIndex p_fg) {
	ERR_FAIL_COND(!console.is_valid());
	ERR_FAIL_INDEX(p_face, TextConsole::FigFontFaceCount);

	// Rendered off-grid so the banner text ends up in the ring buffer like everything else
	// and survives a reflow or a page switch.
	Ref<TextConsole> scratch = newref(TextConsole);
	scratch->load_font(console->get_font());
	scratch->resize(console->get_console_size().width, MAX(8, console->get_console_size().height));
	scratch->logf(p_face, p_msg, p_fg);

	const Size2i size = scratch->get_console_size();
	for (int y = 0; y < scratch->get_cursor().y; ++y) {
		String line;
		bool bank1 = false;
		for (int x = 0; x < size.width; ++x) {
			const TextConsole::cell &c = scratch->_screen[y * size.width + x];
			// Re-emit the bank toggle so the patched connector glyphs survive the round trip
			// through the ring buffer instead of falling back to the CP437 shape.
			if (bool(c.bank) != bank1) {
				line += String::chr(0x01);
				bank1 = !bank1;
			}
			line += String::chr(c.character ? uint8_t(c.character) : ' ');
		}
		if (bank1) {
			line += String::chr(0x01);
		}
		_push_raw_line(line.rstrip(" "), p_fg, TextConsole::COLOR_DEFAULT);
	}
	if (page == PAGE_LOG) {
		_render();
	}
}

