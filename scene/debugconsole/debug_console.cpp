void ConsoleInstance::set_value(const StringName &p_name, const Variant &p_value) {
	const int idx = _find_watch(p_name);
	if (idx >= 0) {
		watches.write[idx].cached = p_value;
	} else {
		Watch w;
		w.name = p_name;
		w.obj = 0;
		w.cached = p_value;
		w.color = TextConsole::COLOR_DEFAULT;
		watches.push_back(w);
	}
	dirty = true;
}

void ConsoleInstance::add_value(const StringName &p_name, const Ref<FuncRef> &p_getter) {
	ERR_FAIL_COND(p_getter.is_null());

	remove_watch(p_name);
	Watch w;
	w.name = p_name;
	w.obj = 0;
	w.getter = p_getter;
	w.color = TextConsole::COLOR_DEFAULT;
	watches.push_back(w);
	dirty = true;
}

void ConsoleInstance::add_var(const StringName &p_name, Object *p_object, const StringName &p_property) {
	ERR_FAIL_NULL(p_object);

	remove_watch(p_name);
	Watch w;
	w.name = p_name;
	w.obj = p_object->get_instance_id();
	w.property = p_property;
	w.color = TextConsole::COLOR_DEFAULT;
	watches.push_back(w);
	dirty = true;
}

void ConsoleInstance::remove_watch(const StringName &p_name) {
	const int idx = _find_watch(p_name);
	if (idx >= 0) {
		watches.remove(idx);
		dirty = true;
	}
}

void ConsoleInstance::clear_watches() {
	watches.clear();
	dirty = true;
}

Array ConsoleInstance::get_watch_names() const {
	Array names;
	for (int i = 0; i < watches.size(); ++i) {
		names.push_back(String(watches[i].name));
	}
	return names;
}

